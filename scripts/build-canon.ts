/** Reads the KJV and writes the versification (verses per chapter) that defines verse ids. */
import fs from "node:fs";
import path from "node:path";
import { ROOT, TRANSLATIONS, allBooks, readUsfmBook } from "./lib.ts";

const kjv = TRANSLATIONS[0];
const counts: number[][] = [];
for (const b of allBooks()) {
  const parsed = readUsfmBook(kjv.dir, b.usfm);
  const chs = [...parsed.chapters.keys()].sort((a, c) => a - c);
  chs.forEach((n, i) => {
    if (n !== i + 1) throw new Error(`${b.name}: chapter gap at ${n}`);
  });
  counts.push(
    chs.map((n) => {
      const ch = parsed.chapters.get(n)!;
      const vs = [...ch.verses.keys()].sort((a, c) => a - c);
      vs.forEach((v, i) => {
        if (v !== i + 1) throw new Error(`${b.name} ${n}: verse gap at ${v}`);
      });
      return vs.length;
    }),
  );
}
const total = counts.flat().reduce((a, c) => a + c, 0);
const chapters = counts.flat().length;
if (total !== 31102 || chapters !== 1189) throw new Error(`unexpected canon: ${total} verses, ${chapters} chapters`);
const body = `// Generated by scripts/build-canon.ts from the KJV. Do not edit.\n// Verses per chapter, by book in canonical order. Total ${total} verses in ${chapters} chapters.\nexport const VERSE_COUNTS: readonly (readonly number[])[] = [\n${counts.map((c) => "  [" + c.join(",") + "],").join("\n")}\n];\n`;
fs.writeFileSync(path.join(ROOT, "src/lib/canon/versification.generated.ts"), body);
console.log(`canon: ${total} verses, ${chapters} chapters`);
