/** Lists the books that have a footnotes file, per translation, in src/lib/data/notes.generated.ts, so the reader never asks for a file that does not exist. */
import fs from "node:fs";
import path from "node:path";
import { OUT } from "./lib.ts";
import { BOOKS } from "../src/lib/canon/books.ts";

const known = new Set(BOOKS.map((b) => b.osis));
const textDir = path.join(OUT, "text");
const lines: string[] = [];
let total = 0;
const translations = fs.readdirSync(textDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
for (const tr of translations) {
  const found = new Set<string>();
  for (const f of fs.readdirSync(path.join(textDir, tr))) {
    const m = /^(.+)\.notes\.json$/.exec(f);
    if (!m) continue;
    if (!known.has(m[1])) throw new Error(`${tr}/${f}: ${m[1]} is not a known book`);
    found.add(m[1]);
  }
  const list = BOOKS.filter((b) => found.has(b.osis)).map((b) => JSON.stringify(b.osis));
  total += list.length;
  lines.push(`  ${tr}: [${list.join(", ")}],`);
}
const body = `// Generated by scripts/build-notes-index.ts. Do not edit.
// Books that have a footnotes file, by translation id. A book that is not listed has no <Book>.notes.json, so the app does not ask for one.
export const NOTES_BOOKS: Readonly<Record<string, readonly string[]>> = {
${lines.join("\n")}
};
`;
fs.writeFileSync(path.join(import.meta.dirname, "..", "src", "lib", "data", "notes.generated.ts"), body);
console.log(`notes index: ${translations.length} translations, ${total} books with notes`);
